# ------------------------------------------------------------------
# Правило сопоставления файла
# ------------------------------------------------------------------
@dataclass
class FileRule:
    """Правило сопоставления файла с парсером и показателем."""

    # Подстрока, которую ищем в base_name (без расширения) без учёта регистра
    name_contains: str

    # Сторона: "БУ" или "ПУ"
    side: Literal["БУ", "ПУ"]

    # Формат файла
    fmt: Literal["excel", "json"]

    # Имя парсера (ключ для реестра парсеров)
    parser_name: str

    # Дополнительные параметры, специфичные для парсера
    params: dict = field(default_factory=dict)


