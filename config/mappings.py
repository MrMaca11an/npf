# ------------------------------------------------------------------

# Маппинг ВидВыплат → показатель для файла «Выплата» (эталонные написания).
VYPLATA_TYPE_MAP: dict[str, str] = {
    "Негосударственная пенсия": "Выплата пенсии",
    "Выкупная сумма (Расторжение)": "Выплата выкупных сумм",
    "Выкупная сумма (Наследникам)": "Выплата наследуемых сумм",
}

# Сопоставление ВидВыплат по ключевым словам — устойчиво к реальным выгрузкам,
# где значения отличаются от эталона опечатками, пробелами и пунктуацией:
#   «Негосударсвенная пенсия» (опечатка), «Выкупная сумма(Расторжение)» (без пробела).
# Правило: (все перечисленные ключевые слова должны встретиться в значении) →
# показатель. Правила проверяются по порядку, первое совпадение выигрывает,
# поэтому более специфичные («наследникам») идут раньше общих.
VYPLATA_KEYWORD_RULES: list[tuple[list[str], str]] = [
    (["выкуп", "наслед"], "Выплата наследуемых сумм"),
    (["наслед"], "Выплата наследуемых сумм"),
    (["выкуп"], "Выплата выкупных сумм"),
    (["расторж"], "Выплата выкупных сумм"),
    (["пенси"], "Выплата пенсии"),
]

